// Writes dist/sitemap.xml and dist/robots.txt after the Astro build.
//
// Both are derived from the build rather than maintained by hand, and for the
// same reason: the route set is conditional. An App's detail page exists only
// once someone has written a body for it, and its privacy route only once there
// is a policy — so a hand-kept sitemap would name routes that 404 the moment an
// App is added to the catalogue before anything is written about it, which is
// the ordinary state of every App on this site today.
//
// Reading the built directory rather than the content collection means the
// sitemap describes what was actually published, not what the route rules were
// expected to produce.
import { readdir, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import astroConfig from '../astro.config.mjs';

// The build directory, overridable so the production-build test can point this
// at its own output rather than at the one wrangler is serving.
const DIST = process.argv[2] ?? 'dist';
// The same single source for the canonical hostname that the headers use: a
// sitemap listing a preview hostname would ask a crawler to index the copy.
const SITE = new URL(astroConfig.site);

/**
 * Every page the build published, as a site-root path with a trailing slash.
 *
 * A page is a directory holding an `index.html` — which is what Astro's default
 * `directory` build format emits, and which leaves `404.html` out on its own,
 * correctly: a crawler asked to index the not-found page would report the site
 * as having a duplicate of it under every missing URL.
 */
async function publishedRoutes(dir = DIST) {
  const routes = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) routes.push(...(await publishedRoutes(path)));
    else if (entry.name === 'index.html') {
      const directory = relative(DIST, dir);
      routes.push(directory === '' ? '/' : `/${directory.split(sep).join('/')}/`);
    }
  }
  return routes;
}

const routes = (await publishedRoutes()).sort();
if (!routes.includes('/')) throw new Error('The build produced no home page.');

/*
  A slug comes from a filename, and a filename may hold an `&`. Escaping is three
  lines here and a malformed public XML file if it is left out.
*/
const escapeXml = (value) =>
  value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes.map((route) => `  <url><loc>${escapeXml(new URL(route, SITE).href)}</loc></url>`).join('\n')}
</urlset>
`;

/*
  No `Disallow` line: everything published is meant to be indexed, and the copies
  that are not — every hostname that is not the apex — are held back by
  `X-Robots-Tag: noindex` instead. A robots file cannot do that job, because it
  is one file served under every hostname the Worker answers to.
*/
const robots = `# Generated by scripts/emit-crawler-files.mjs — do not edit by hand.
User-agent: *
Allow: /

Sitemap: ${new URL('/sitemap.xml', SITE).href}
`;

await writeFile(join(DIST, 'sitemap.xml'), sitemap);
await writeFile(join(DIST, 'robots.txt'), robots);
console.log(`[crawler] wrote sitemap.xml with ${routes.length} routes, and robots.txt`);
